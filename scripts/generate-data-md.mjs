#!/usr/bin/env node
/**
 * Generates DATA.md from data/manifest.json and data/notes/*.md.
 *
 * - data/manifest.json: one entry per dataset (issuer, source, dates,
 *   record count, next expected update). It is the source of truth.
 * - data/notes/*.md, in file-name order: the prose for each section. A note
 *   that starts with `<!-- datasets: a b -->` is about those datasets, and
 *   their manifest facts are printed under its heading.
 *
 * The site's /data page is built from DATA.md (site/scripts/generate.mjs).
 *
 *   node scripts/generate-data-md.mjs           # writes DATA.md
 *   node scripts/generate-data-md.mjs --check   # exit 1 if DATA.md is stale
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(
  readFileSync(join(root, 'data', 'manifest.json'), 'utf8'),
);
const dataVersion = readFileSync(
  join(root, 'src', 'data-version.ts'),
  'utf8',
).match(/dataVersion = '([\d-]+)'/)[1];
const notesDir = join(root, 'data', 'notes');
const notes = readdirSync(notesDir)
  .filter((f) => f.endsWith('.md'))
  .sort()
  .map((f) => readFileSync(join(notesDir, f), 'utf8'));

const byId = new Map(manifest.map((e) => [e.id, e]));
const cell = (s) => String(s ?? '').replaceAll('|', '\\|');
const period = (e) => `${e.effectiveFrom} to ${e.effectiveTo ?? 'now'}`;

function facts(e) {
  return [
    `- **Dataset:** \`${e.file}\` (id \`${e.id}\`), ${e.recordCount.toLocaleString('en-US')} records. ${e.coverage}.`,
    `- **Source:** ${e.issuer}, ${e.sourceReference} (${e.sourceUrl}), ${e.sourceDate ? `dated ${e.sourceDate}` : 'undated'}; retrieved ${e.retrievedAt}, checked ${e.checkedAt}.`,
    `- **Applies:** ${period(e)}.`,
    `- **Next expected update:** ${e.nextExpectedUpdate} (${e.updateCadence.charAt(0).toLowerCase()}${e.updateCadence.slice(1)}).`,
  ].join('\n');
}

const table = [
  '| Dataset | Records | Issuer | Source date | Retrieved | Applies | Next update |',
  '| --- | ---: | --- | --- | --- | --- | --- |',
  ...[...manifest]
    .sort((a, b) => (a.id < b.id ? -1 : 1))
    .map(
      (e) =>
        `| [${cell(e.title)}](${e.sourceUrl}) (\`${e.file}\`) | ${e.recordCount.toLocaleString('en-US')} | ${cell(e.issuer)} | ${e.sourceDate ?? 'undated'} | ${e.retrievedAt} | ${period(e)} | ${e.nextExpectedUpdate} |`,
    ),
].join('\n');

const covered = new Set();
const sections = notes.map((text) => {
  const tag = text.match(/^<!-- datasets: ([^>]+?) -->\n/);
  if (!tag) return text.trim();
  const ids = tag[1].split(/\s+/);
  const body = text.slice(tag[0].length).trim();
  const [heading, ...rest] = body.split('\n');
  const block = ids
    .map((id) => {
      const entry = byId.get(id);
      if (!entry) throw new Error(`data/notes: unknown dataset "${id}"`);
      covered.add(id);
      return facts(entry);
    })
    .join('\n');
  return `${heading}\n\n${block}\n${rest.join('\n')}`.trim();
});
const missing = manifest.filter((e) => !covered.has(e.id)).map((e) => e.id);
if (missing.length)
  throw new Error(`data/notes: no section for ${missing.join(', ')}`);

const [intro, ...rest] = sections;
const out = `# Data sources

<!-- Generated by scripts/generate-data-md.mjs from data/manifest.json and
data/notes/. Edit those, not this file. -->

**Data version: ${dataVersion}**

Every dataset has an entry in [data/manifest.json](data/manifest.json): its
issuer, official source and reference, the dates it was issued, retrieved
and applies to, its record count and when it is next expected to change.
Every port exposes it with \`getDataInfo(id)\` and \`listDataInfo()\`, and CI
checks it against the data.

${table}

${intro}

${rest.join('\n\n')}
`;

const target = join(root, 'DATA.md');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== out) {
    console.error(
      'DATA.md is out of date: run node scripts/generate-data-md.mjs',
    );
    process.exit(1);
  }
  console.log('DATA.md is up to date');
} else {
  writeFileSync(target, out);
  console.log(`DATA.md: ${manifest.length} datasets, ${notes.length} notes`);
}
