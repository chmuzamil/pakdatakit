import { describe, expect, it } from 'vitest';
import {
  createMerchantQr,
  createRaastP2PQr,
  parseRaastQr,
} from '../src/raast.js';

const IBAN = 'PK36SCBL0000001123456702';

/** SBP's sample merchant QR from Annex-A of the QR standard (CRC 5376). */
const SBP_SAMPLE =
  '00020101021202164000123456789012041653451234567890121516634512345678901227420010A0000007360124PK73FAYS35553900000000005204599953035865802PK5916AZIZGeneralStore6007KARACHI62890117234567854321234560211032400000000316AZIZGeneralStore0513123876543212307124567890987656304' +
  '5376';

describe('createRaastP2PQr', () => {
  it('builds a static P2P payload', () => {
    const payload = createRaastP2PQr({ iban: IBAN });
    // Same layout as QR codes generated by banking apps.
    expect(payload).toMatch(
      /^0002020102110202000424PK36SCBL00000011234567021004[0-9A-F]{4}$/,
    );
    expect(payload).toContain(`0424${IBAN}`);
    expect(parseRaastQr(payload)).toMatchObject({
      kind: 'p2p',
      dynamic: false,
      crcValid: true,
      iban: IBAN,
      ibanValid: true,
      amount: null,
    });
  });

  it('builds a dynamic P2P payload with amount and expiry', () => {
    const payload = createRaastP2PQr({
      iban: IBAN,
      amount: 1500,
      expiresAt: new Date(2026, 10, 13, 23, 59),
    });
    // Same layout as dynamic QR codes from banking apps (JazzCash, Mashreq).
    expect(payload).toMatch(
      /^0002020102120202000424PK36SCBL00000011234567020504150007121311202623591004[0-9A-F]{4}$/,
    );
  });

  it('writes whole amounts without decimals', () => {
    const expiresAt = new Date(2026, 10, 13, 23, 59);
    expect(createRaastP2PQr({ iban: IBAN, amount: 100, expiresAt })).toContain(
      '0503100',
    );
    expect(
      createRaastP2PQr({ iban: IBAN, amount: 1500.5, expiresAt }),
    ).toContain('05071500.50');
  });

  it('parses amount, expiry and details', () => {
    const payload = createRaastP2PQr({
      iban: 'pk36 scbl 0000 0011 2345 6702',
      amount: 1500,
      expiresAt: new Date(2026, 10, 13, 23, 59),
      bankName: 'Standard Chartered',
      particulars: 'Rent October',
    });
    expect(parseRaastQr(payload)).toMatchObject({
      kind: 'p2p',
      dynamic: true,
      crcValid: true,
      iban: IBAN,
      amount: 1500,
      expiresAt: '2026-11-13T23:59',
      bankName: 'Standard Chartered',
      particulars: 'Rent October',
    });
  });

  it('rejects invalid input', () => {
    expect(() => createRaastP2PQr({ iban: 'PK00XXXX' })).toThrow(RangeError);
    expect(() => createRaastP2PQr({ iban: IBAN, amount: -5 })).toThrow(
      RangeError,
    );
    // Banking apps reject dynamic QR codes without an expiry.
    expect(() => createRaastP2PQr({ iban: IBAN, amount: 100 })).toThrow(
      /expiresAt/,
    );
    expect(() =>
      createRaastP2PQr({ iban: IBAN, amount: 100, expiresAt: new Date('x') }),
    ).toThrow(RangeError);
    expect(() =>
      createRaastP2PQr({ iban: IBAN, particulars: 'x'.repeat(31) }),
    ).toThrow(RangeError);
  });
});

describe('createMerchantQr', () => {
  const merchantAccount = {
    fields: { '00': 'A000000736', '01': IBAN },
  };

  it('builds a static merchant payload', () => {
    const payload = createMerchantQr({
      merchantAccount,
      merchantName: 'Aziz General Store',
      city: 'Karachi',
      mcc: '5411',
    });
    expect(payload.startsWith('000201010211')).toBe(true);
    expect(payload).toContain('5303586');
    expect(payload).toContain('5802PK');
    expect(parseRaastQr(payload)).toMatchObject({
      kind: 'merchant',
      dynamic: false,
      crcValid: true,
      iban: IBAN,
      merchantName: 'Aziz General Store',
      city: 'Karachi',
      mcc: '5411',
    });
  });

  it('builds a dynamic bill payload with a due date', () => {
    const payload = createMerchantQr({
      merchantAccount,
      merchantName: 'K-Electric',
      city: 'Karachi',
      amount: 4250.5,
      billNumber: 'INV-1001',
      dueDate: new Date(2026, 10, 25),
      amountAfterDueDate: 4500,
    });
    expect(parseRaastQr(payload)).toMatchObject({
      dynamic: true,
      crcValid: true,
      amount: 4250.5,
      billNumber: 'INV-1001',
      dueDate: '2026-11-25',
      amountAfterDueDate: 4500,
    });
  });

  it('enforces SBP field limits', () => {
    const base = { merchantAccount, city: 'Karachi' };
    expect(() =>
      createMerchantQr({ ...base, merchantName: 'x'.repeat(26) }),
    ).toThrow(RangeError);
    expect(() =>
      createMerchantQr({ ...base, merchantName: 'Shop', city: 'x'.repeat(16) }),
    ).toThrow(RangeError);
    expect(() =>
      createMerchantQr({
        ...base,
        merchantName: 'Shop',
        dueDate: new Date(),
      }),
    ).toThrow(RangeError);
    expect(() =>
      createMerchantQr({
        ...base,
        merchantName: 'Shop',
        merchantAccount: { tag: '02', fields: { '00': 'x' } },
      }),
    ).toThrow(RangeError);
  });
});

describe('parseRaastQr', () => {
  it("parses SBP's sample merchant QR", () => {
    expect(parseRaastQr(SBP_SAMPLE)).toMatchObject({
      kind: 'merchant',
      dynamic: true,
      crcValid: true,
      iban: 'PK73FAYS3555390000000000',
      merchantName: 'AZIZGeneralStore',
      city: 'KARACHI',
      mcc: '5999',
    });
  });

  it('detects a corrupted payload', () => {
    const corrupted = SBP_SAMPLE.replace('KARACHI', 'LAHOREE');
    expect(parseRaastQr(corrupted)?.crcValid).toBe(false);
  });

  it('returns null for non-QR text', () => {
    expect(parseRaastQr('hello world')).toBeNull();
    expect(parseRaastQr('0002990102')).toBeNull();
  });
});

describe('createRaastP2PQr scheme', () => {
  it('uses scheme 00 by default and allows 30', () => {
    expect(createRaastP2PQr({ iban: IBAN })).toContain('020200');
    const sbp = createRaastP2PQr({ iban: IBAN, scheme: '30' });
    expect(sbp).toContain('020230');
    expect(parseRaastQr(sbp)?.crcValid).toBe(true);
  });
});
